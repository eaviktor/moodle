CREATE TABLE users
(
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT
);

CREATE TABLE calendars
(
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users (id)
);

CREATE TABLE slots
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    calendar_id BIGINT      NOT NULL REFERENCES calendars (id),
    start_time  TIMESTAMPTZ NOT NULL,
    end_time    TIMESTAMPTZ NOT NULL,
    status      VARCHAR(64) NOT NULL DEFAULT 'FREE'
);

CREATE INDEX slots_calendar_id_start_time_idx ON slots (calendar_id, start_time);

CREATE TABLE meetings
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slot_id BIGINT NOT NULL UNIQUE REFERENCES slots (id),
    title   TEXT   NOT NULL,
    description TEXT
);

CREATE TABLE meeting_participants
(
    meeting_id BIGINT NOT NULL REFERENCES meetings (id),
    name       TEXT   NOT NULL,
    email      TEXT
);

CREATE INDEX meeting_participants_meeting_id_idx ON meeting_participants (meeting_id);
